"""Описание API для OpenAPI/Swagger: группы эндпоинтов и типовые ответы с ошибками."""
import schemas

ERROR_DESCRIPTIONS = {
    304: "Не изменилось (ETag совпал) — клиент берёт ответ из своего кэша",
    400: "Ошибка бизнес-логики",
    401: "Нет токена, токен истёк или недействителен",
    403: "Недостаточно прав (нужна роль admin)",
    404: "Объект не найден или принадлежит другому пользователю",
    413: "Файл слишком большой",
    415: "Неподдерживаемый тип файла",
    422: "Ошибка валидации входных данных",
    429: "Слишком много запросов — повторите позже (см. заголовок Retry-After)",
}


def err(*codes: int) -> dict:
    """responses=err(401, 404) — добавляет в документацию эндпоинта описания ошибок."""
    return {
        code: {"description": ERROR_DESCRIPTIONS[code], **({} if code == 304 else {"model": schemas.ErrorOut})}
        for code in codes
    }


AUTH_ERRORS = err(401)
OWNER_ERRORS = err(401, 404, 422)

